namespace Tgs.SerialNumberGenerator.UnitTests;

public class GuidSortTests
{
	[Fact]
	public void Guid排序_Part1小_Part2大()
	{
		// Arrange
		var id1 = Guid.Parse("fff9322d-8401-0000-0002-000064923304");
		var id2 = Guid.Parse("fef9323d-8401-0000-0002-000064923304");

		// Act
		var actual = id1.CompareTo(id2);

		// Assert
		Assert.Equal(1, actual);
	}

	[Fact]
	public void Guid排序_由第一個位元比對到最後一個()
	{
		// Arrange
		var ids = new[]
		{
			Guid.Parse("00000000-0000-0000-0000-000000000011"),
			Guid.Parse("00000000-0000-0000-0000-000000001100"),
			Guid.Parse("00000000-0000-0000-0000-000000110000"),
			Guid.Parse("00000000-0000-0000-0000-000011000000"),
			Guid.Parse("00000000-0000-0000-0000-001100000000"),
			Guid.Parse("00000000-0000-0000-0000-110000000000"),
			Guid.Parse("00000000-0000-0000-0011-000000000000"),
			Guid.Parse("00000000-0000-0000-1100-000000000000"),
			Guid.Parse("00000000-0000-0011-0000-000000000000"),
			Guid.Parse("00000000-0000-1100-0000-000000000000"),
			Guid.Parse("00000000-0011-0000-0000-000000000000"),
			Guid.Parse("00000000-1100-0000-0000-000000000000"),
			Guid.Parse("00000011-0000-0000-0000-000000000000"),
			Guid.Parse("00001100-0000-0000-0000-000000000000"),
			Guid.Parse("00110000-0000-0000-0000-000000000000"),
			Guid.Parse("11000000-0000-0000-0000-000000000000")
		};

		var expected = new[]
		{
			Guid.Parse("11000000-0000-0000-0000-000000000000"),
			Guid.Parse("00110000-0000-0000-0000-000000000000"),
			Guid.Parse("00001100-0000-0000-0000-000000000000"),
			Guid.Parse("00000011-0000-0000-0000-000000000000"),
			Guid.Parse("00000000-1100-0000-0000-000000000000"),
			Guid.Parse("00000000-0011-0000-0000-000000000000"),
			Guid.Parse("00000000-0000-1100-0000-000000000000"),
			Guid.Parse("00000000-0000-0011-0000-000000000000"),
			Guid.Parse("00000000-0000-0000-1100-000000000000"),
			Guid.Parse("00000000-0000-0000-0011-000000000000"),
			Guid.Parse("00000000-0000-0000-0000-110000000000"),
			Guid.Parse("00000000-0000-0000-0000-001100000000"),
			Guid.Parse("00000000-0000-0000-0000-000011000000"),
			Guid.Parse("00000000-0000-0000-0000-000000110000"),
			Guid.Parse("00000000-0000-0000-0000-000000001100"),
			Guid.Parse("00000000-0000-0000-0000-000000000011")
		};

		// Act
		var actual = ids.OrderDescending();

		// Assert
		Assert.Equal(expected, actual);
	}
}
